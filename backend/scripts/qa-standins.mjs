// FIT-QA stand-in parts: simple shapes generated in code for the accessory types that have no published part yet (rear bumper, front
// lip, rear diffuser, side skirt, roof rack). TEST ONLY: written to 3d-source/qa-standins (git-ignored), never published to customers,
// no licence / credits involved. Every node and material is named QA_STANDIN_*.
//   node scripts/qa-standins.mjs        -> 3d-source/qa-standins/<type>.glb
import { Document, NodeIO } from '@gltf-transform/core';
import { mkdirSync, writeFileSync } from 'node:fs'; import { resolve } from 'node:path'; import { ROOT } from './vehicle-audit-lib.mjs';

const OUT = resolve(ROOT, '3d-source/qa-standins'); mkdirSync(OUT, { recursive: true });
/** Axis-aligned boxes [x0,y0,z0,x1,y1,z1] (metres; x = across the car, y = up, z = along) into one flat-shaded mesh. */
function glb(name, boxes, color) {
  const pos = [], nor = [], idx = [];
  const faces = [[0, -1], [0, 1], [1, -1], [1, 1], [2, -1], [2, 1]];
  for (const b of boxes) for (const [ax, sg] of faces) {
    const u = (ax + 1) % 3, v = (ax + 2) % 3, base = pos.length / 3;
    for (const [i, j] of [[0, 0], [1, 0], [1, 1], [0, 1]]) { const p = [0, 0, 0]; p[ax] = sg > 0 ? b[ax + 3] : b[ax]; p[u] = i ? b[u + 3] : b[u]; p[v] = j ? b[v + 3] : b[v]; pos.push(...p); const n = [0, 0, 0]; n[ax] = sg; nor.push(...n); }
    idx.push(...(sg > 0 ? [base, base + 1, base + 2, base, base + 2, base + 3] : [base, base + 2, base + 1, base, base + 3, base + 2]));
  }
  const doc = new Document(), buf = doc.createBuffer(), mat = doc.createMaterial('QA_STANDIN_' + name).setBaseColorFactor([...color, 1]).setRoughnessFactor(0.6).setMetallicFactor(0);
  const prim = doc.createPrimitive().setMaterial(mat)
    .setAttribute('POSITION', doc.createAccessor().setType('VEC3').setArray(new Float32Array(pos)).setBuffer(buf))
    .setAttribute('NORMAL', doc.createAccessor().setType('VEC3').setArray(new Float32Array(nor)).setBuffer(buf))
    .setIndices(doc.createAccessor().setType('SCALAR').setArray(new Uint32Array(idx)).setBuffer(buf));
  doc.createScene().addChild(doc.createNode('QA_STANDIN_' + name).setMesh(doc.createMesh('QA_STANDIN_' + name).addPrimitive(prim)));
  return new NodeIO().writeBinary(doc);
}
/** A part curved along x (the middle stands out by `bow` metres toward +z): n slices of the same profile boxes. */
const curved = (W, n, bow, profile) => Array.from({ length: n }, (_, i) => {
  const x0 = -W / 2 + (i * W) / n, x1 = x0 + W / n, xm = (x0 + x1) / 2, dz = bow * (1 - (2 * xm / W) ** 2);
  return profile.map(([y0, z0, y1, z1]) => [x0, y0, z0 + dz, x1, y1, z1 + dz]);
}).flat();
const grey = [0.35, 0.36, 0.38];
const parts = {
  // a wrap-round shell: face, top lip, bottom return; 1.8 m wide, 0.36 m tall
  'rear-bumper': glb('REAR_BUMPER', curved(1.8, 30, 0.08, [[0, 0.2, 0.36, 0.24], [0.33, 0, 0.36, 0.24], [0, 0, 0.03, 0.22]]), grey),
  // a 1.7 m blade, 12 cm deep, 18 mm thick, its middle 4 cm further forward
  'front-lip': glb('FRONT_LIP', curved(1.7, 30, 0.04, [[0, 0, 0.018, 0.12]]), [0.08, 0.08, 0.09]),
  // a 1.3 m plate with five 6 cm fins under it
  'rear-diffuser': glb('REAR_DIFFUSER', [[-0.65, 0, 0, 0.65, 0.02, 0.32], ...[-0.5, -0.25, 0, 0.25, 0.5].map(x => [x - 0.006, -0.06, 0.02, x + 0.006, 0, 0.3])], [0.08, 0.08, 0.09]),
  // one sill: 2.2 m long, 11 cm tall, 6 cm deep, with a 2 cm step at the bottom
  'side-skirt': glb('SIDE_SKIRTS', [[0, 0.02, -1.1, 0.06, 0.11, 1.1], [0, 0, -1.1, 0.08, 0.02, 1.1]], grey),
  // two cross bars 1.15 m wide, 75 cm apart, on four 7 cm feet
  'roof-rack': glb('ROOF_RACK', [[-0.575, 0.07, -0.39, 0.575, 0.1, -0.36], [-0.575, 0.07, 0.36, 0.575, 0.1, 0.39],
    ...[-0.55, 0.53].flatMap(x => [-0.39, 0.36].map(z => [x, 0, z, x + 0.025, 0.07, z + 0.03]))], [0.12, 0.12, 0.13]),
};
for (const [n, p] of Object.entries(parts)) writeFileSync(resolve(OUT, n + '.glb'), await p);
writeFileSync(resolve(OUT, 'README.md'), '# FIT-QA stand-ins (TEST ONLY)\nGenerated by backend/scripts/qa-standins.mjs: plain boxes for the accessory types without a published part. Never published to customers; no licence.\n');
