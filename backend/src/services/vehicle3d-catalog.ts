import { existsSync, readFileSync, writeFileSync, renameSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_ROOT = fileURLToPath(new URL("../../../", import.meta.url));
export const CATALOG_PATH = new URL("../../../docs/3d/models.json", import.meta.url);
export type Offset = {x:number;y:number;z:number;scale:number};
export type ViewerConfig = {
  bakedPaint?: {hue:[number,number];sat:number;ref:number};
  centerX?:number;keepBox?:{y:[number,number];z:[number,number];names?:string[]};
  zones?:{frontBumper?:{meshes:string[];box:{x:[number,number];y:[number,number];z:[number,number]}}};
  key: string; generation: string; lengthM: number; rotateY: number; preRotateX?: number;
  groundOffset: number; paintNodes: string[]; paintMaterials: string[]; rimsSwappable: boolean;
  wing: { x: number; y: number; z: number; scale: number }; rack: { x: number; y: number; z: number; scale: number };
  credit: { title: string; author: string; url: string; license: string };
};
export type ModelMetadata = {
  key: string; file: string; make: string; model: string; code: string; title: string;
  author: string; authorUrl?: string; url: string; license: string; inApp?: boolean;
  finalStatus?: string; viewerConfig?: ViewerConfig; [key: string]: unknown;
};
export type Manifest = Record<string, ModelMetadata>;
export const readManifest = (): Manifest => JSON.parse(readFileSync(CATALOG_PATH, "utf8"));
export const safeKey = (s: string) => /^[a-z0-9][a-z0-9-]{0,150}$/.test(s);
export function activeModels(manifest = readManifest()) {
  return Object.values(manifest).filter(e => e.inApp !== false && e.viewerConfig && e.viewerConfig.key === e.file && safeKey(e.file)
    && existsSync(path.join(REPO_ROOT, "backend/public/3d", `${e.file}.glb`)))
    .map(e => e.viewerConfig!);
}

/** Generate from the manifest, preserving complete hand-tuned viewer configurations. */
export function catalogFiles(manifest: Manifest): Map<string, string> {
  const mobile = fileURLToPath(new URL("../../../mobile/src/features/car3d/models.ts", import.meta.url));
  const credits = fileURLToPath(new URL("../../../docs/3d/CREDITS.md", import.meta.url));
  const ts = readFileSync(mobile, "utf8").replace(/^\uFEFF/, "");
  const list = Object.values(manifest).filter(e => e.inApp !== false && e.viewerConfig);
  if (Object.values(manifest).some(e => e.inApp !== false && (!e.viewerConfig || e.viewerConfig.key !== e.file || !safeKey(e.file)))) throw new Error("Active catalog entry is missing valid viewer configuration");
  if (new Set(list.map(e => e.file)).size !== list.length) throw new Error("Duplicate active catalog filename");
  const start = ts.indexOf("export const CAR_MODELS: CarModel[] = [");
  const end = ts.indexOf("\n];", start);
  if (start < 0 || end < 0) throw new Error("Cannot find CAR_MODELS generated block");
  const next = (ts.slice(0, start) + "export const CAR_MODELS: CarModel[] = [\n  // Generated from docs/3d/models.json by vehicle3d-catalog.ts.\n"
    + list.map(e => `  ${JSON.stringify(e.viewerConfig)},`).join("\n") + ts.slice(end)).trimEnd() + "\n";
  const cell = (s: string) => s.replace(/[|\r\n<>]/g, " ").replace(/\[/g, "(").replace(/\]/g, ")");
  const link = (s: string) => /^https:\/\/[^\s()]+$/.test(s) ? s : "";
  const creditEntries: ModelMetadata[] = [];
  for (const entry of list) {
    creditEntries.push(entry);
    // Immutable prior versions remain downloadable after explicit replacement; retain their attribution too.
    let previous = entry.previousCatalogMetadata as ModelMetadata | undefined;
    while (previous) {
      if (previous.inApp !== false && safeKey(previous.file) && existsSync(path.join(REPO_ROOT,"backend/public/3d",`${previous.file}.glb`)))
        creditEntries.push({ ...previous, title: `${previous.title} (previous approved version)` });
      previous = previous.previousCatalogMetadata as ModelMetadata | undefined;
    }
  }
  const rows = creditEntries.map(e => `| ${cell(`${e.make} ${e.model} ${e.code}`)} | ${link(e.url) ? `[${cell(e.title)}](${link(e.url)})` : cell(e.title)} | ${cell(e.author)} | ${cell(e.license)} |`);
  const block = `<!-- models: generated by backend/scripts/optimize-3d.ts -->\n| Generation | Model | Author | License |\n|---|---|---|---|\n${rows.join("\n")}\n<!-- /models -->`;
  const md = readFileSync(credits, "utf8");
  return new Map([[fileURLToPath(CATALOG_PATH), JSON.stringify(manifest, null, 2) + "\n"], [mobile, next],
    [credits, /<!-- models:[\s\S]*?<!-- \/models -->/.test(md) ? md.replace(/<!-- models:[\s\S]*?<!-- \/models -->/, block) : md + "\n" + block + "\n"]]);
}

export function atomicWrite(file: string, data: string | Buffer) {
  const temporary = file + ".vehicle3d.tmp";
  writeFileSync(temporary, data);
  renameSync(temporary, file);
}
export function writeCatalog(manifest: Manifest) {
  for (const [file, text] of catalogFiles(manifest)) atomicWrite(file, text);
}
