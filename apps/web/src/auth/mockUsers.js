const PASSWORD = 'Test123!'
const { APPROVED, PENDING } = ACCOUNT_STATUS

function base({ id, role, status = APPROVED, name, email, phone, createdAt, tagIds = [] }) {
  const reviewed = status === APPROVED && ROLES_NEEDING_APPROVAL.includes(role)
  return {
    id,
    role,
    status,
    rejectionReason: null,
    createdAt,
    reviewedAt: reviewed ? createdAt : null,
    verification: reviewed ? { method: 'documents', note: 'Seed account', reviewedBy: 'u-1' } : null,
    suspended: false,
    suspendedAt: null,
    suspensionReason: null,
    tagIds,
    name,
    email,
    phone,
    password: PASSWORD,
    notificationPrefs: { ...DEFAULT_NOTIFICATION_PREFS },
    sessionsRevokedAt: null,
  }
}

// skills: [skill, years] or [skill, years, { status, rejectionReason, submittedAt }]
function mechanic({
  skills,
  color,
  workshopName,
  city,
  address,
  description = '',
  serviceModes = ['workshop'],
  onSiteCities = [],
  makes = [],
  base: basePoint = null,
  photoCaptions,
  ...account
}) {
  return {
    ...base({ ...account, role: ROLES.MECHANIC }),
    profilePhoto: avatarPhoto(account.name, color),
    city,
    workshopName,
    address,
    description,
    serviceModes,
    onSiteCities,
    makes,
    base: basePoint,
    skills: skills.map(([skill, years, review = {}], i) => ({
      id: `${account.id}-skill-${i + 1}`,
      skill,
      years,
      status: account.status === PENDING ? SKILL_STATUS.PENDING : SKILL_STATUS.APPROVED,
      rejectionReason: null,
      submittedAt: account.createdAt,
      ...review,
      certificate: samplePdf(`${slug(skill)}-certificate-${account.id}.pdf`, `${skill} certificate`, [
        `Awarded to: ${account.name}`,
        `Workshop: ${workshopName}, ${city}`,
        `Years of experience: ${years}`,
      ]),
    })),
    workshopPhotos: photoCaptions.map((caption, i) =>
      placePhoto(`${account.id}-workshop-${i + 1}.svg`, caption, color),
    ),
    pendingChanges: [],
  }
}

// trucks: [type, maxWeightKg, plateNumber, caption] plus an optional { status, reviewStatus, submittedAt }
// base: where the trucks are parked ({ lat, lng }, approximate). towServices: TOW_SERVICES values
// in features/logistics/constants.js.
function towCompany({ trucks, color, city, address, serviceArea, description, base: basePoint, towServices, ...account }) {
  return {
    ...base({ ...account, role: ROLES.TOW }),
    profilePhoto: logoImage(account.name, color),
    city,
    address,
    description,
    serviceArea,
    base: basePoint,
    towServices,
    businessLicense: samplePdf(`${account.id}-business-license.pdf`, 'Business license', [account.name, city]),
    trucks: trucks.map(([type, maxWeightKg, plateNumber, caption, extra = {}], i) => ({
      id: `${account.id}-truck-${i + 1}`,
      plateNumber,
      type,
      maxWeightKg,
      photos: [truckPhoto(`${account.id}-truck-${i + 1}.svg`, caption, color)],
      registration: samplePdf(`${account.id}-truck-${i + 1}-registration.pdf`, 'Vehicle registration', [plateNumber]),
      insurance: samplePdf(`${account.id}-truck-${i + 1}-insurance.pdf`, 'Insurance certificate', [plateNumber]),
      status: 'available',
      reviewStatus: account.status === PENDING ? REVIEW_STATUS.PENDING : REVIEW_STATUS.APPROVED,
      rejectionReason: null,
      submittedAt: account.createdAt,
      ...extra,
    })),
    pendingChanges: [],
  }
}

function partsShop({ color, city, address, description, pendingChanges = [], ...account }) {
  return {
    ...base({ ...account, role: ROLES.PARTS_SHOP }),
    profilePhoto: logoImage(account.name, color),
    city,
    address,
    description,
    businessLicense: samplePdf(`${account.id}-business-license.pdf`, 'Commercial registration', [account.name, city]),
    extraDocuments: [],
    shopPhotos: [placePhoto(`${account.id}-shop-1.svg`, `${account.name} storefront`, color)],
    pendingChanges,
  }
}

